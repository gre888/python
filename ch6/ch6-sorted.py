# 初始化待排序的整數串列（陣列），共 5 個元素
a = [4, -15, 20, 13, -11]
# 印出標題提示「排序前：」，end = '' 表示列印完後不換行，繼續接在同一行
print('排  序  前 : ', end = '')
# 使用 for 迴圈印出排序前的初始陣列內容 
# range(5) 會產生索引值 0, 1, 2, 3, 4
for i in range(5):
     # 格式化輸出：i 為索引號，a[i]:3d 表示將數值靠右對齊並佔據至少 3 個字元寬度 
     # end = ' ' 表示每個元素之間用兩個空格隔開，不換行
     print(f' a[{i:d}]={a[i]:3d}', end = '  ') # a[0]= 4 a[1]=-15 a[2]= 20 a[3]= 13 a[4]=-11
 
# 外層迴圈：控制排序的回合（Pass） 
# range(1, 5) 會執行 loop = 1, 2, 3, 4，共 4 回合（N 個元素需要 N-1 回合）
 
for loop in range(1, 5):
 
     # 內層迴圈：比較與交換相鄰的兩個元素 
     # range(0, 5 - loop)：每一回合結束後，最大值會被送到最後面，因此比較次數會逐回合減 1 
     # 外圈 loop = 1，內圈 range 0 ~ (5 - 1) => index = 0, 1, 2, 3  比 4 次 a[0] 比 a[1] -> a[1] 比 a[2] -> a[2] 比 a[3] ->  a[3] 比 a[4]    
     # 外圈 loop = 2，內圈 range 0 ~ (5 - 2) => index = 0, 1, 2 比 3 次 a[0] 比 a[1] -> a[1] 比 a[2] -> a[2] 比 a[3]  
     # 外圈 loop = 3，內圈 range 0 ~ (5 - 3) => index = 0, 2    比 2 次 a[0] 比 a[1] -> a[1] 比 a[2] 
     # 外圈 loop = 4，內圈 range 0 ~ (5 - 4) => index = 0, 1    比 1 次 a[0] 比 a[1] 
     for index in range(0, (5-loop)):
         # 如果前一個元素比後一個元素大，代表順序錯誤，需要進行交換（由小到大排序）
         if a[index] > a[index+1] :
             # 使用暫存變數 temp 進行經典的三步驟值交換
             temp = a[index]        # 1. 先將左邊的值備份到 temp
             a[index] = a[index+1]  # 2. 將右邊較小的值覆蓋到左邊
             a[index+1] = temp      # 3. 將備份的值放到右邊
     # 內層迴圈結束，代表該回合（loop）的比較與交換已完成        
     print()
 
     # 印出當前是第幾次（第幾回合）排序的標題，並且不換行
     print(f'第 {loop} 次排列: ' , end = '')
 
     # 使用 for 迴圈印出當前回合排序後的陣列最新狀態
     for j in range(5):
         print(f' a[{j:d}]={a[j]:3d}', end = '  ') 